import assert from 'node:assert/strict';
const base=process.env.AI_TEST_BASE_URL;
if(!base||!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(base))throw Error('Isolated localhost required');
const api=base+'/api/owner/business/slicing';
assert.equal((await fetch(api)).status,401);
assert.equal((await fetch(api,{method:'POST',headers:{origin:'https://invalid.example'},body:'{}'})).status,403);
assert.equal((await fetch(base+'/api/slicing-worker',{method:'POST',body:'{}'})).status,401);
assert.equal((await fetch(base+'/api/slicing-worker/asset?claimId='+crypto.randomUUID())).status,401);
const login=await fetch(base+'/api/owner/login',{method:'POST',headers:{origin:base,'Content-Type':'application/json'},body:JSON.stringify({password:process.env.AI_TEST_OWNER_PASSWORD||'local-owner'})});
assert.equal(login.status,200);const cookie=login.headers.get('set-cookie').split(';')[0];
const headers={origin:base,cookie,'Content-Type':'application/json'};
const owner=async data=>fetch(api,{method:'POST',headers,body:JSON.stringify(data)});
assert.equal((await owner({action:'publish'})).status,400);
assert.equal((await fetch(api,{headers})).headers.get('cache-control'),'no-store');
const pairResponse=await owner({action:'pair'});assert.equal(pairResponse.status,200);
const pair=await pairResponse.json();assert.match(pair.token,/^[a-f0-9]{64}$/);
const worker=async data=>fetch(base+'/api/slicing-worker',{method:'POST',headers:{authorization:'Bearer '+pair.token,'Content-Type':'application/json'},body:JSON.stringify(data)});
assert.equal((await worker({action:'configure'})).status,400);
assert.equal((await worker({action:'heartbeat'})).status,200);
assert.equal((await worker({action:'heartbeat'})).status,429);
assert.equal((await fetch(base+'/api/slicing-worker/asset?claimId='+crypto.randomUUID(),{headers:{authorization:'Bearer '+pair.token}})).status,409);
assert.equal((await fetch(base+'/api/slicing-worker',{method:'POST',headers:{authorization:'Bearer '+pair.token},body:'x'.repeat(20001)})).status,413);
assert.equal((await owner({action:'revoke',workerId:pair.workerId})).status,200);
assert.equal((await worker({action:'claim'})).status,401);
assert.ok(!JSON.stringify(await (await fetch(api,{headers})).json()).includes(pair.token));
console.log('Slicing API auth and scope tests passed');
