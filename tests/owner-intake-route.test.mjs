import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';
import {z} from 'zod';
import {intakeSchema} from '../lib/ai-center/intake.ts';
let owner=false,origin=true,calls=[];
const exports={};
const source=await fs.readFile(new URL('../app/api/owner/business/intake/route.ts',import.meta.url),'utf8');
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports,require(name){
  if(name==='next/server')return {NextResponse:{json:(body,options={})=>({body,status:options.status||200})}};
  if(name==='zod')return {z};
  if(name==='@/lib/owner-auth')return {requestIsOwner:async()=>owner};
  if(name==='@/lib/owner-api')return {sameOrigin:()=>origin};
  if(name==='@/lib/ai-center/intake')return {intakeSchema};
  if(name==='@/lib/request-store')return {createOwnerStoredRequest:async value=>{calls.push(value);return {requestCode:'REQ-TEST'};}};
  throw Error('Unexpected import '+name);
}});
const draft={key:'c8592098-6fdc-4627-afc9-5dd460265330',name:'A possible project',description:'Ask for dimensions.',quantity:1,stage:'on-hold'};
const request=value=>({text:async()=>JSON.stringify(value)});
assert.equal((await exports.POST(request(draft))).status,401);
owner=true;origin=false;assert.equal((await exports.POST(request(draft))).status,403);
origin=true;assert.equal((await exports.POST(request({...draft,stage:'deposit-paid'}))).status,400);
assert.equal((await exports.POST(request({...draft,email:'test@example.com'}))).status,400);
assert.equal((await exports.POST(request({...draft,customerEmail:'test@example.com'}))).status,400);
assert.equal(calls.length,0);
assert.equal((await exports.POST(request(draft))).status,200);
assert.equal(calls.length,1);assert.equal(calls[0].ownerTrackingStatus,'on-hold');assert.equal(calls[0].status,'reviewing');
assert.equal(calls[0].email,'');assert.equal(calls[0].ownerIntakeKey,draft.key);
assert.equal((await exports.POST(request({...draft,customerEmail:'test@example.com',customerPhone:'555-0100',contactReviewed:true}))).status,200);
assert.equal(calls[1].email,'test@example.com');assert.equal(calls[1].phone,'555-0100');assert.equal(calls[1].emailNotifications,false);
console.log('Intake route requires owner/origin, rejects contacts/payments, saves only reviewed request fields.');
