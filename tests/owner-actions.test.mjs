import assert from 'node:assert/strict';
import {ownerActions} from '../lib/ai-center/owner-actions.ts';
const base={jobs:[],projects:[],checks:[],rows:[]};
assert.equal(ownerActions(base).length,0);
const items=ownerActions({...base,jobs:[{id:'a',kind:'plan',status:'spend-review',boundCents:1},{id:'b',kind:'research',status:'failed'},{id:'c',kind:'design',status:'running'}]});
assert.equal(items.length,2);
assert.match(items[0].detail,/\$0.01/);
assert.equal(items[0].target,'approval-a');
assert.equal(items[1].target,'task-b');
const project={id:'p',name:'Tray',stage:'release',business:'mesh',revisions:[{tests:[{passed:true}]}],printTestNeedsReview:true,release:null,salesNeedsReview:true};
const actions=ownerActions({...base,projects:[project],checks:[{id:'tax',label:'Tax',status:'action',detail:'Review tax'},{id:'owner',label:'Owner',status:'ready',detail:'Configured'}]});
assert(actions.some(x=>x.title==='Test the current print: Tray'));
assert(actions.some(x=>x.id==='cost-p'));
assert(!actions.some(x=>x.id==='setup-owner'));
const shipping=ownerActions({...base,rows:[{order:{id:'paid',status:'paid',refundedCents:0},shipping:null},{order:{id:'refund',status:'paid',refundedCents:10},shipping:null},{order:{id:'sent',status:'paid',refundedCents:0},shipping:{state:'handed-off',email:{state:'sent'}}}]});
assert.equal(shipping.length,1);
assert.equal(shipping[0].target,'shipping-paid');
assert.equal(ownerActions({...base,rows:[{order:{id:'r',status:'paid',refundedCents:0},shipping:{state:'reconcile',email:{state:'pending'}}}]}).length,1);
assert.equal(ownerActions({...base,checks:[{id:'live-carrier',label:'Live carrier',status:'action',detail:'Use a production carrier key'}]})[0].target,'catalog-shipping-heading');
console.log('Owner actions: approvals, current physical tests, setup and paid shipping checks passed');
