import assert from 'node:assert/strict';
const base=process.env.AI_TEST_BASE_URL;
if(!base||!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(base))throw Error('Local test URL required. Never run against production.');
const api=base+'/api/owner/business';
assert.equal((await fetch(api)).status,401);
if(process.env.AI_TEST_PRODUCTION==='true')assert.equal((await fetch(api,{method:'POST',headers:{'Content-Type':'application/json'},body:'{"action":"run"}'})).status,403);
assert.equal((await fetch(api,{method:'POST',headers:{origin:'https://invalid.example','Content-Type':'application/json'},body:'{"action":"run"}'})).status,403);
const login=await fetch(base+'/api/owner/login',{method:'POST',headers:{origin:base,'Content-Type':'application/json'},body:JSON.stringify({password:process.env.AI_TEST_OWNER_PASSWORD})});
assert.equal(login.status,200);
const cookie=login.headers.get('set-cookie').split(';')[0];
const headers={origin:base,cookie,'Content-Type':'application/json'};
const post=async body=>fetch(api,{method:'POST',headers,body:JSON.stringify(body)});
const initial=await fetch(api,{headers});assert.equal(initial.status,200);assert.equal(initial.headers.get('cache-control'),'no-store');
const initialData=await initial.json();assert.equal(initialData.settings.paidEnabled,false);
assert.equal((await post({action:'configure',settings:{...initialData.settings,monthlyLimitCents:-1}})).status,400);
const key=crypto.randomUUID();
assert.equal((await post({action:'enqueue',task:{agent:'products',kind:'idea',brief:'Local integration test: printable checklist.',key}})).status,200);
assert.equal((await post({action:'enqueue',task:{agent:'products',kind:'idea',brief:'Local integration test: printable checklist.',key}})).status,200);
assert.equal((await post({action:'run'})).status,200);
const read=async()=>await (await fetch(api,{headers})).json();
const job=(await read()).jobs.find(j=>j.key===key);assert.equal(job.status,'review');assert.equal(job.chargedCents,0);
assert.equal((await post({action:'decide',id:job.id,decision:'approve'})).status,200);
assert.equal((await read()).jobs.find(j=>j.id===job.id).status,'ready');
assert.equal((await post({action:'decide',id:job.id,decision:'approve'})).status,409);
assert.equal((await post({action:'send',id:job.id})).status,400);
assert.equal((await post({action:'publish',id:job.id})).status,400);
assert.equal((await fetch(api,{method:'POST',headers:{...headers,origin:'https://invalid.example'},body:'{"action":"run"}'})).status,403);
console.log('AI local HTTP owner access, CSRF, validation, idempotency, draft review, and prohibited-action checks passed.');
