import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
const {SlicingRecords}=await import('../lib/ai-center/slicing-store.ts');
const {defaultMaterialPlan}=await import('../lib/ai-center/slicing-types.ts');
const db=new DatabaseSync(':memory:');
const records=new SlicingRecords(db);
const now=new Date('2026-10-12T12:00:00Z');
const input={projectId:crypto.randomUUID(),revisionId:crypto.randomUUID(),sha256:'a'.repeat(64),quantity:1,profileId:'x2d-04-020-pla-basic',profileHash:'b'.repeat(64),materialPlan:defaultMaterialPlan()};
assert.equal(input.materialPlan.lines[0].colorName,'Black');
assert.throws(()=>records.enqueue({...input,materialPlan:{...input.materialPlan,use:'outdoor'}}),/PETG/);
assert.throws(()=>records.enqueue({...input,materialPlan:{...input.materialPlan,use:'unknown'}}),/use/);
assert.throws(()=>records.enqueue({...input,materialPlan:{...input.materialPlan,multicolor:true}}),/multicolor/i);
const job=records.enqueue(input,now);
assert.equal(records.enqueue(input,now).id,job.id);
const pair=records.pair(now);
assert.equal(records.authenticate(pair.token,now),pair.workerId);
assert.throws(()=>records.authenticate('bad',now),/credential/);
const claim=records.claim(pair.workerId,now);
assert.equal(claim.job.id,job.id);
assert.equal(records.claim(pair.workerId,now),null);
const late=new Date(now.getTime()+301000);
const retry=records.claim(pair.workerId,late);
assert.notEqual(retry.claimId,claim.claimId);
const result={sourceSha256:input.sha256,profileHash:input.profileHash,slicerVersion:'2.8',grams:8,partGrams:null,filaments:[{slot:1,consumedGrams:8,purgeGrams:null,towerGrams:null}],colorChanges:0,seconds:1200,sizeMm:[60,36,12],warnings:[]};
assert.throws(()=>records.finish(pair.workerId,claim.claimId,result,late),/claim/);
assert.equal(records.finish(pair.workerId,retry.claimId,result,late).state,'completed');
assert.equal(records.finish(pair.workerId,retry.claimId,result,late).state,'completed');
assert.throws(()=>records.finish(pair.workerId,retry.claimId,{...result,seconds:1300},late),/result/);
const other=records.enqueue({...input,quantity:2},now);
records.cancel(other.id);
assert.equal(records.claim(pair.workerId,late),null);
const third=records.enqueue({...input,quantity:3},now);
records.claim(pair.workerId,now);
records.claim(pair.workerId,late);
records.claim(pair.workerId,new Date(late.getTime()+301000));
assert.equal(records.snapshot(late).jobs.find(j=>j.id===third.id).state,'failed');
records.retry(third.id,late);
assert.equal(records.claim(pair.workerId,late).job.id,third.id);
records.cancel(third.id);
records.retry(third.id,late);
assert.equal(records.get(third.id).state,'queued');
assert.ok(!JSON.stringify(records.snapshot(now)).includes(pair.token));
assert.throws(()=>records.authenticate(pair.token,new Date(now.getTime()+31*86400000)),/credential/);
records.limit(pair.workerId,'heartbeat',now);
assert.throws(()=>new SlicingRecords(db).limit(pair.workerId,'heartbeat',now),/Rate/);
records.revoke(pair.workerId);
assert.throws(()=>records.authenticate(pair.token,now),/credential/);
assert.throws(()=>records.claim(pair.workerId,now),/credential/);
db.close();
console.log('Slicing store tests passed');
